-- 用户名唯一、按用户名/UUID 搜索，以及仅限好友的私信。

-- 历史默认昵称先改为基于 UUID 的唯一可读名称，再处理其他重复昵称。
update public.profiles
set nickname = '用户' || upper(substr(id::text, 1, 8))
where nickname = '我';

with ranked as (
    select id, row_number() over (
        partition by lower(nickname) order by created_at, id
    ) as position
    from public.profiles
)
update public.profiles p
set nickname = left(p.nickname, 12) || '_' || upper(substr(p.id::text, 1, 6))
from ranked r
where p.id = r.id and r.position > 1;

create unique index if not exists profiles_nickname_unique_idx
    on public.profiles(lower(nickname));

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    referrer_id uuid;
begin
    select p.id into referrer_id
    from public.profiles p
    where p.invitation_code = nullif(new.raw_user_meta_data ->> 'invite_code', '');

    insert into public.profiles (id, nickname, invited_by)
    values (
        new.id,
        coalesce(
            nullif(new.raw_user_meta_data ->> 'nickname', ''),
            '用户' || upper(substr(new.id::text, 1, 8))
        ),
        referrer_id
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

revoke all on function public.handle_new_user() from public, anon, authenticated;

create table if not exists public.friend_messages (
    id bigint generated by default as identity primary key,
    sender_id uuid not null references public.profiles(id) on delete cascade,
    receiver_id uuid not null references public.profiles(id) on delete cascade,
    content text not null check (char_length(content) between 1 and 1000),
    created_at timestamptz not null default now(),
    check (sender_id <> receiver_id)
);

create index if not exists friend_messages_sender_receiver_time_idx
    on public.friend_messages(sender_id, receiver_id, created_at desc);
create index if not exists friend_messages_receiver_sender_time_idx
    on public.friend_messages(receiver_id, sender_id, created_at desc);

alter table public.friend_messages enable row level security;

drop policy if exists friend_messages_select_participant on public.friend_messages;
create policy friend_messages_select_participant on public.friend_messages
    for select to authenticated
    using (
        sender_id = (select auth.uid())
        or receiver_id = (select auth.uid())
    );

-- 即使误授 INSERT，数据库也要求发送者就是本人且双方确实存在好友关系。
drop policy if exists friend_messages_insert_friend on public.friend_messages;
create policy friend_messages_insert_friend on public.friend_messages
    for insert to authenticated
    with check (
        sender_id = (select auth.uid())
        and exists (
            select 1 from public.friendships f
            where f.user_low = least(sender_id, receiver_id)
              and f.user_high = greatest(sender_id, receiver_id)
        )
    );

revoke all on table public.friend_messages from anon;
grant select on table public.friend_messages to authenticated;

-- 会话列表：最近一条消息与最近活跃排序。
drop function if exists public.list_friends();
create function public.list_friends()
returns table (
    friend_id uuid,
    nickname text,
    avatar_emoji text,
    friends_since timestamptz,
    last_message text,
    last_message_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
    current_uid uuid := (select auth.uid());
begin
    if current_uid is null then
        raise exception 'authentication_required' using errcode = '42501';
    end if;

    return query
    select p.id, p.nickname, p.avatar_emoji, f.created_at,
           latest.content, latest.created_at
    from public.friendships f
    join public.profiles p
      on p.id = case
          when f.user_low = current_uid then f.user_high
          else f.user_low
      end
    left join lateral (
        select m.content, m.created_at
        from public.friend_messages m
        where (m.sender_id = current_uid and m.receiver_id = p.id)
           or (m.receiver_id = current_uid and m.sender_id = p.id)
        order by m.created_at desc
        limit 1
    ) latest on true
    order by coalesce(latest.created_at, f.created_at) desc;
end;
$$;

revoke all on function public.list_friends() from public, anon;
grant execute on function public.list_friends() to authenticated;

-- 用户名使用不区分大小写的精确搜索；UUID 也使用精确匹配。
create or replace function public.search_users(p_query text)
returns table (
    user_id uuid,
    nickname text,
    avatar_emoji text
)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
    current_uid uuid := (select auth.uid());
    cleaned text := trim(coalesce(p_query, ''));
begin
    if current_uid is null then
        raise exception 'authentication_required' using errcode = '42501';
    end if;
    if cleaned = '' then
        return;
    end if;

    return query
    select p.id, p.nickname, p.avatar_emoji
    from public.profiles p
    where p.id <> current_uid
      and (
          lower(p.nickname) = lower(cleaned)
          or lower(p.id::text) = lower(cleaned)
      )
    limit 10;
end;
$$;

revoke all on function public.search_users(text) from public, anon;
grant execute on function public.search_users(text) to authenticated;

create or replace function public.list_friend_messages(p_friend_id uuid)
returns table (
    message_id bigint,
    sender_id uuid,
    content text,
    created_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
    current_uid uuid := (select auth.uid());
begin
    if current_uid is null then
        raise exception 'authentication_required' using errcode = '42501';
    end if;
    if not exists (
        select 1 from public.friendships f
        where f.user_low = least(current_uid, p_friend_id)
          and f.user_high = greatest(current_uid, p_friend_id)
    ) then
        raise exception 'not_friends' using errcode = '42501';
    end if;

    return query
    select recent.message_id, recent.sender_id, recent.content, recent.created_at
    from (
        select m.id as message_id, m.sender_id, m.content, m.created_at
        from public.friend_messages m
        where (m.sender_id = current_uid and m.receiver_id = p_friend_id)
           or (m.receiver_id = current_uid and m.sender_id = p_friend_id)
        order by m.created_at desc
        limit 200
    ) recent
    order by recent.created_at asc;
end;
$$;

create or replace function public.send_friend_message(p_friend_id uuid, p_content text)
returns table (
    message_id bigint,
    sender_id uuid,
    content text,
    created_at timestamptz
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    current_uid uuid := (select auth.uid());
    cleaned text := trim(coalesce(p_content, ''));
    new_id bigint;
    new_time timestamptz;
begin
    if current_uid is null then
        raise exception 'authentication_required' using errcode = '42501';
    end if;
    if cleaned = '' or char_length(cleaned) > 1000 then
        raise exception 'invalid_message';
    end if;
    if not exists (
        select 1 from public.friendships f
        where f.user_low = least(current_uid, p_friend_id)
          and f.user_high = greatest(current_uid, p_friend_id)
    ) then
        raise exception 'not_friends' using errcode = '42501';
    end if;

    insert into public.friend_messages (sender_id, receiver_id, content)
    values (current_uid, p_friend_id, cleaned)
    returning id, created_at into new_id, new_time;

    return query select new_id, current_uid, cleaned, new_time;
end;
$$;

revoke all on function public.list_friend_messages(uuid) from public, anon;
revoke all on function public.send_friend_message(uuid, text) from public, anon;
grant execute on function public.list_friend_messages(uuid) to authenticated;
grant execute on function public.send_friend_message(uuid, text) to authenticated;
