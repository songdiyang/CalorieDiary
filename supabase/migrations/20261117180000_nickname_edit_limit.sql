-- 用户名（昵称）自助修改：个人页与设置页共用，每 7 天最多 3 次。
-- 修改历史写入 nickname_changes；客户端只能通过 update_nickname 修改，
-- 不能直接 PATCH profiles.nickname 绕过次数限制（见文件末尾的列权限收紧）。

create table if not exists public.nickname_changes (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.profiles(id) on delete cascade,
    nickname text not null,
    changed_at timestamptz not null default now()
);

create index if not exists nickname_changes_user_time_idx
    on public.nickname_changes(user_id, changed_at desc);

alter table public.nickname_changes enable row level security;
revoke all on table public.nickname_changes from anon, authenticated;

-- 查询当前 7 天窗口内的修改次数与剩余次数，供界面展示。
create or replace function public.nickname_change_status()
returns table (
    used integer,
    remaining integer,
    next_available_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
    current_uid uuid := (select auth.uid());
    used_count integer;
begin
    if current_uid is null then
        raise exception 'authentication_required' using errcode = '42501';
    end if;

    select count(*)::integer into used_count
    from public.nickname_changes c
    where c.user_id = current_uid
      and c.changed_at > now() - interval '7 days';

    return query
    select used_count,
           greatest(0, 3 - used_count),
           case
               when used_count >= 3 then (
                   select min(c.changed_at) + interval '7 days'
                   from public.nickname_changes c
                   where c.user_id = current_uid
                     and c.changed_at > now() - interval '7 days'
               )
               else null::timestamptz
           end;
end;
$$;

-- 修改用户名：去首尾空白后 1-20 个字符，禁止控制字符；
-- 7 天内最多成功修改 3 次，与当前昵称相同不计次数。
create or replace function public.update_nickname(p_nickname text)
returns table (nickname text, remaining integer)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    current_uid uuid := (select auth.uid());
    cleaned text := btrim(coalesce(p_nickname, ''));
    used_count integer;
    current_nickname text;
begin
    if current_uid is null then
        raise exception 'authentication_required' using errcode = '42501';
    end if;
    if char_length(cleaned) = 0
       or char_length(cleaned) > 20
       or cleaned ~ '[[:cntrl:]]' then
        raise exception 'invalid_nickname' using errcode = '22023';
    end if;

    -- 锁住本人资料行，避免并发请求同时通过次数校验。
    select p.nickname into current_nickname
    from public.profiles p
    where p.id = current_uid
    for update;

    if current_nickname is null then
        raise exception 'profile_not_found' using errcode = '42501';
    end if;

    if current_nickname = cleaned then
        select count(*)::integer into used_count
        from public.nickname_changes c
        where c.user_id = current_uid
          and c.changed_at > now() - interval '7 days';
        return query select current_nickname, greatest(0, 3 - used_count);
        return;
    end if;

    select count(*)::integer into used_count
    from public.nickname_changes c
    where c.user_id = current_uid
      and c.changed_at > now() - interval '7 days';

    if used_count >= 3 then
        raise exception 'nickname_change_limit' using errcode = '42901';
    end if;

    update public.profiles p
    set nickname = cleaned,
        updated_at = now()
    where p.id = current_uid;

    insert into public.nickname_changes (user_id, nickname)
    values (current_uid, cleaned);

    return query select cleaned, 2 - used_count;
end;
$$;

revoke all on function public.nickname_change_status() from public, anon, authenticated;
revoke all on function public.update_nickname(text) from public, anon, authenticated;
grant execute on function public.nickname_change_status() to authenticated;
grant execute on function public.update_nickname(text) to authenticated;

-- 客户端只保留头像列的更新权限，昵称必须走 update_nickname 才能计入次数。
revoke update on table public.profiles from anon, authenticated;
grant update (avatar_emoji) on table public.profiles to authenticated;
