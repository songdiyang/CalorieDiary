-- 个人资料仅本人可读、可建、可改；小组展示所需的昵称保存在成员表中。
drop policy if exists profiles_select_own on public.profiles;
create policy profiles_select_own on public.profiles
    for select to authenticated
    using (id = (select auth.uid()));

drop policy if exists profiles_insert_own on public.profiles;
create policy profiles_insert_own on public.profiles
    for insert to authenticated
    with check (id = (select auth.uid()));

drop policy if exists profiles_update_own on public.profiles;
create policy profiles_update_own on public.profiles
    for update to authenticated
    using (id = (select auth.uid()))
    with check (id = (select auth.uid()));

-- 创建者可立即读取自己的小组；其他成员必须已经加入才能读取。
drop policy if exists groups_select_member on public.groups;
create policy groups_select_member on public.groups
    for select to authenticated
    using (
        owner_id = (select auth.uid())
        or public.is_group_member(id)
    );

drop policy if exists groups_insert_owner on public.groups;
create policy groups_insert_owner on public.groups
    for insert to authenticated
    with check (owner_id = (select auth.uid()));

drop policy if exists groups_update_owner on public.groups;
create policy groups_update_owner on public.groups
    for update to authenticated
    using (owner_id = (select auth.uid()))
    with check (owner_id = (select auth.uid()));

drop policy if exists groups_delete_owner on public.groups;
create policy groups_delete_owner on public.groups
    for delete to authenticated
    using (owner_id = (select auth.uid()));

-- 邀请码就是 groups.id。加入时只能为自己写入成员记录，不能冒充其他用户。
drop policy if exists group_members_select_member on public.group_members;
create policy group_members_select_member on public.group_members
    for select to authenticated
    using (
        user_id = (select auth.uid())
        or public.is_group_member(group_id)
    );

drop policy if exists group_members_insert_self on public.group_members;
create policy group_members_insert_self on public.group_members
    for insert to authenticated
    with check (user_id = (select auth.uid()));

drop policy if exists group_members_update_self on public.group_members;
create policy group_members_update_self on public.group_members
    for update to authenticated
    using (user_id = (select auth.uid()))
    with check (user_id = (select auth.uid()));

drop policy if exists group_members_delete_self_or_owner on public.group_members;
create policy group_members_delete_self_or_owner on public.group_members
    for delete to authenticated
    using (
        user_id = (select auth.uid())
        or public.is_group_owner(group_id)
    );

