-- 小组只返回昵称和当日热量合计，不返回食物名称、克重或单条明细。
create or replace function public.get_group_daily_totals(
    p_group_id text,
    p_date date
)
returns table (
    user_id uuid,
    nickname text,
    avatar_emoji text,
    total_calories bigint
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    if not public.is_group_member(p_group_id) then
        raise exception 'not_group_member' using errcode = '42501';
    end if;

    return query
    select
        gm.user_id,
        gm.nickname,
        gm.avatar_emoji,
        coalesce(sum(me.calories), 0)::bigint as total_calories
    from public.group_members gm
    left join public.meal_entries me
        on me.user_id = gm.user_id
       and me.entry_date = p_date
    where gm.group_id = p_group_id
    group by gm.user_id, gm.nickname, gm.avatar_emoji;
end;
$$;

