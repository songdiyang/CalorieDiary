-- 好友联机热量：账户资料、小组、成员与私人饮食记录。
-- 所有业务操作使用 authenticated 角色；匿名角色不能访问这些表。

create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    nickname text not null default '我' check (char_length(nickname) between 1 and 20),
    avatar_emoji text not null default '🐰',
    calorie_goal integer not null default 1800 check (calorie_goal between 500 and 10000),
    water_goal integer not null default 1500 check (water_goal between 0 and 20000),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.groups (
    id text primary key check (id ~ '^[0-9]{6}$'),
    name text not null default '我们的小组' check (char_length(name) between 1 and 30),
    owner_id uuid not null references public.profiles(id) on delete cascade,
    calorie_goal integer not null default 1800 check (calorie_goal between 500 and 10000),
    created_at timestamptz not null default now()
);

create table if not exists public.group_members (
    group_id text not null references public.groups(id) on delete cascade,
    user_id uuid not null references public.profiles(id) on delete cascade,
    nickname text not null default '我' check (char_length(nickname) between 1 and 20),
    avatar_emoji text not null default '🐰',
    joined_at timestamptz not null default now(),
    last_active_at timestamptz not null default now(),
    primary key (group_id, user_id)
);

create table if not exists public.meal_entries (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.profiles(id) on delete cascade,
    entry_date date not null,
    meal_type smallint not null check (meal_type between 0 and 3),
    food_name text not null check (char_length(food_name) between 1 and 80),
    emoji text not null default '🍴',
    grams integer not null check (grams > 0),
    calories integer not null check (calories >= 0),
    recorded_at timestamptz not null default now(),
    created_at timestamptz not null default now()
);

create index if not exists group_members_user_id_idx
    on public.group_members(user_id);
create index if not exists groups_owner_id_idx
    on public.groups(owner_id);
create index if not exists meal_entries_user_date_idx
    on public.meal_entries(user_id, entry_date);

-- 注册后自动建立个人资料，App 不需要用客户端传入的用户 ID 创建身份。
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    insert into public.profiles (id, nickname)
    values (
        new.id,
        coalesce(nullif(new.raw_user_meta_data ->> 'nickname', ''), '我')
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_user();

-- 这些 SECURITY DEFINER 函数只返回布尔值，用来避免 group_members 的 RLS 自引用递归。
create or replace function public.is_group_member(p_group_id text)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
    select exists (
        select 1
        from public.group_members
        where group_id = p_group_id
          and user_id = (select auth.uid())
    );
$$;

create or replace function public.is_group_owner(p_group_id text)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
    select exists (
        select 1
        from public.groups
        where id = p_group_id
          and owner_id = (select auth.uid())
    );
$$;

