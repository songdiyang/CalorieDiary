-- 群聊创建、加入、消息与每日热量分享。

create or replace function public.generate_group_id()
returns text
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
    candidate text;
begin
    loop
        candidate := lpad(floor(random() * 1000000)::integer::text, 6, '0');
        exit when not exists (select 1 from public.groups where id = candidate);
    end loop;
    return candidate;
end;
$$;

create or replace function public.create_group(
    p_name text,
    p_calorie_goal integer default 1800
)
returns table (
    group_id text,
    name text,
    owner_id uuid,
    calorie_goal integer,
    created_at timestamptz
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    current_uid uuid := (select auth.uid());
    new_group_id text;
    clean_name text := trim(coalesce(p_name, ''));
    new_goal integer := least(greatest(p_calorie_goal, 500), 10000);
begin
    if current_uid is null then
        raise exception 'authentication_required' using errcode = '42501';
    end if;
    if clean_name = '' or char_length(clean_name) > 30 then
        raise exception 'invalid_group_name';
    end if;
    new_group_id := public.generate_group_id();

    insert into public.groups (id, name, owner_id, calorie_goal)
    values (new_group_id, clean_name, current_uid, new_goal);

    insert into public.group_members (group_id, user_id, nickname, avatar_emoji)
    select new_group_id, p.id, p.nickname, p.avatar_emoji
    from public.profiles p where p.id = current_uid;

    return query
    select g.id, g.name, g.owner_id, g.calorie_goal, g.created_at
    from public.groups g where g.id = new_group_id;
end;
$$;

create or replace function public.join_group(p_group_id text)
returns table (
    group_id text,
    name text,
    owner_id uuid,
    calorie_goal integer,
    created_at timestamptz
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    current_uid uuid := (select auth.uid());
begin
    if current_uid is null then
        raise exception 'authentication_required' using errcode = '42501';
    end if;
    if not exists (select 1 from public.groups g where g.id = p_group_id) then
        raise exception 'group_not_found';
    end if;

    insert into public.group_members (group_id, user_id, nickname, avatar_emoji)
    select p_group_id, p.id, p.nickname, p.avatar_emoji
    from public.profiles p where p.id = current_uid
    on conflict (group_id, user_id) do nothing;

    return query
    select g.id, g.name, g.owner_id, g.calorie_goal, g.created_at
    from public.groups g where g.id = p_group_id;
end;
$$;

create table if not exists public.group_messages (
    id bigint generated by default as identity primary key,
    group_id text not null references public.groups(id) on delete cascade,
    sender_id uuid not null references public.profiles(id) on delete cascade,
    content text not null check (char_length(content) between 1 and 1000),
    message_type text not null default 'text' check (message_type in ('text', 'calorie_share')),
    calories integer check (calories between 0 and 100000),
    entry_date date,
    created_at timestamptz not null default now(),
    check (
        (message_type = 'text' and calories is null)
        or (message_type = 'calorie_share' and calories is not null and entry_date is not null)
    )
);

create index if not exists group_messages_group_time_idx
    on public.group_messages(group_id, created_at desc);

alter table public.group_messages enable row level security;

drop policy if exists group_messages_select_member on public.group_messages;
create policy group_messages_select_member on public.group_messages
    for select to authenticated
    using (exists (
        select 1 from public.group_members gm
        where gm.group_id = group_messages.group_id
          and gm.user_id = (select auth.uid())
    ));

drop policy if exists group_messages_insert_member on public.group_messages;
create policy group_messages_insert_member on public.group_messages
    for insert to authenticated
    with check (
        sender_id = (select auth.uid())
        and exists (
            select 1 from public.group_members gm
            where gm.group_id = group_messages.group_id
              and gm.user_id = (select auth.uid())
        )
    );

revoke all on table public.group_messages from anon;
grant select on table public.group_messages to authenticated;

create or replace function public.list_groups()
returns table (
    group_id text,
    name text,
    owner_id uuid,
    calorie_goal integer,
    created_at timestamptz,
    last_message text,
    last_message_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
    current_uid uuid := (select auth.uid());
begin
    if current_uid is null then
        raise exception 'authentication_required' using errcode = '42501';
    end if;

    return query
    select g.id, g.name, g.owner_id, g.calorie_goal, g.created_at,
           latest.content, latest.created_at
    from public.groups g
    left join lateral (
        select m.content, m.created_at
        from public.group_messages m
        where m.group_id = g.id
        order by m.created_at desc
        limit 1
    ) latest on true
    where exists (
        select 1 from public.group_members gm
        where gm.group_id = g.id and gm.user_id = current_uid
    )
    order by coalesce(latest.created_at, g.created_at) desc;
end;
$$;

create or replace function public.list_group_messages(p_group_id text)
returns table (
    message_id bigint,
    sender_id uuid,
    content text,
    message_type text,
    calories integer,
    entry_date date,
    created_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
    current_uid uuid := (select auth.uid());
begin
    if current_uid is null then
        raise exception 'authentication_required' using errcode = '42501';
    end if;
    if not exists (
        select 1 from public.group_members gm
        where gm.group_id = p_group_id and gm.user_id = current_uid
    ) then
        raise exception 'not_group_member' using errcode = '42501';
    end if;

    return query
    select recent.message_id, recent.sender_id, recent.content,
           recent.message_type, recent.calories, recent.entry_date, recent.created_at
    from (
        select m.id as message_id, m.sender_id, m.content, m.message_type,
               m.calories, m.entry_date, m.created_at
        from public.group_messages m
        where m.group_id = p_group_id
        order by m.created_at desc
        limit 200
    ) recent
    order by recent.created_at asc;
end;
$$;

create or replace function public.send_group_message(
    p_group_id text,
    p_content text,
    p_message_type text default 'text',
    p_calories integer default null,
    p_entry_date date default null
)
returns table (
    message_id bigint,
    sender_id uuid,
    content text,
    message_type text,
    calories integer,
    entry_date date,
    created_at timestamptz
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    current_uid uuid := (select auth.uid());
    cleaned text := trim(coalesce(p_content, ''));
    new_id bigint;
    new_time timestamptz;
begin
    if current_uid is null then
        raise exception 'authentication_required' using errcode = '42501';
    end if;
    if cleaned = '' or char_length(cleaned) > 1000 then
        raise exception 'invalid_message';
    end if;
    if not exists (
        select 1 from public.group_members gm
        where gm.group_id = p_group_id and gm.user_id = current_uid
    ) then
        raise exception 'not_group_member' using errcode = '42501';
    end if;
    if p_message_type not in ('text', 'calorie_share') then
        raise exception 'invalid_message_type';
    end if;

    insert into public.group_messages as target (
        group_id, sender_id, content, message_type, calories, entry_date
    ) values (
        p_group_id, current_uid, cleaned, p_message_type, p_calories, p_entry_date
    )
    returning target.id, target.created_at into new_id, new_time;

    return query
    select new_id, current_uid, cleaned, p_message_type, p_calories, p_entry_date, new_time;
end;
$$;

revoke all on function public.generate_group_id() from public, anon;
revoke all on function public.create_group(text, integer) from public, anon;
revoke all on function public.join_group(text) from public, anon;
revoke all on function public.list_groups() from public, anon;
revoke all on function public.list_group_messages(text) from public, anon;
revoke all on function public.send_group_message(text, text, text, integer, date) from public, anon;

grant execute on function public.generate_group_id() to authenticated;
grant execute on function public.create_group(text, integer) to authenticated;
grant execute on function public.join_group(text) to authenticated;
grant execute on function public.list_groups() to authenticated;
grant execute on function public.list_group_messages(text) to authenticated;
grant execute on function public.send_group_message(text, text, text, integer, date) to authenticated;
